#!/usr/bin/env bash
# build_textures.sh -- rebuild (or verify) the shipped BMPs under
# data/textures/ from their generators. There are FOUR recipes: 64
# procedural BMPs from `generate_textures`, `spell_sprite_atlas.bmp` from
# `spell_sprite_atlas_builder` (T417), `item_icons{0,1}.bmp` from
# `item_icon_atlas_builder` (T430) and `spell_icons{gems,spells,buff}.bmp` +
# `spell_icon_holder.bmp` from `spell_icon_atlas_builder` (B1077) -- the last
# three lifted from the official client's own art rather than generated.
#
# T403 (board B260). Sibling of scripts/build_willeq_pack.sh: that script
# rebuilds willeq.eqe1 from its two input sources, one of which is this
# directory. Before T403 the directory itself had no recipe -- P26 retired
# tools/generate_textures.cpp as dead, and for a year the 926-line TU that
# defines every procedural texture the client ships
# (src/client/graphics/texture_generators.cpp) compiled in NO CMake target
# while its output kept shipping. B225 is the direct consequence: the
# particle atlas shipped alpha-less and nobody could run the code that
# proved it wrong.
#
# Usage:
#   scripts/build_textures.sh [--check] [--bin-dir DIR] [--textures-dir DIR]
#                             [--pin-file PATH] [--write-pins] [--keep-temp]
#
#   --check        Regenerate into a temp directory and verify, without
#                  writing anything into the tree. Exit 0 only if all three
#                  assertions below hold. This is what the ctest test runs.
#   --write-pins   Rewrite the pin file from the CURRENT contents of
#                  data/textures/. Only after a deliberate asset change.
#   (no flag)      Regenerate in place into data/textures/.
#
# --check asserts three things, and each catches a different drift:
#
#   1. PIN     every file in data/textures/ hashes to its pinned sha256, and
#              the directory holds exactly the pinned set. Catches a
#              hand-edit or a stray file -- including one nothing regenerates.
#   2. RECIPE  for every file the generator owns, the regenerated bytes equal
#              the shipped bytes. Catches a generator edit that silently
#              stops matching the asset (or an asset edited without its
#              generator).
#   3. CENSUS  the three tools together write exactly the pinned set of
#              names. Catches a generator added or removed without updating
#              the pins.
#
# Determinism note (T403, board B268): the generators must be bit-identical
# across optimisation levels, or this check is a coin toss that depends on
# which build tree ran it. Two noise hashes overflowed signed `int` (UB) and
# GCC folded them differently at -O0 and -O2 -- the particle atlas came out
# 157 texels apart. Both now run in `uint32_t`. If you add a generator, keep
# its arithmetic defined: unsigned integer hashes, no reliance on FP
# association.
#
# NOT_REPRODUCIBLE below is the exemption list for assertion 2. It is
# deliberately tiny and every entry needs a board item; an entry here means
# "the shipped bytes are NOT derived from the tree", which is the state B260
# exists to end. It is not a place to park a failing generator.

set -u

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"

# ── The exemption list for assertion 2 (RECIPE) ─────────────────────────────
# EMPTY since T427 (board B265 closed). detail_atlas.bmp was the last and only
# entry: the shipped bytes were the generator's output pushed through the
# retired tool's Irrlicht SOFTWARE-driver texture round trip, which did two
# things at once -- quantised every channel to A1R5G5B5 (all 786,432 pixel
# bytes a multiple of 8; 18,913 pixels) and PREMULTIPLIED RGB by alpha, which
# is invisible wherever alpha is 0 or 255 and therefore showed up in exactly
# the twelve footprint tiles, the only tiles in the whole atlas whose painter
# writes a fractional alpha (`SColor(alpha * 200, ...)` in
# DetailTextureAtlas::drawFootprintLeft/Right; 10,596 pixels). T427 measured
# that regenerating it moves ZERO golden pixels (gles2_zone_benchmark never
# instantiates DetailManager, so no gate frame contains a detail-atlas texel)
# and ZERO pack bytes (ETC1 is fixed-rate), and shipped the generator's output.
# Every entry added here needs a board item and means "the shipped bytes are
# NOT derived from the tree", which is the state B260 exists to end. It is not
# a place to park a failing generator.
NOT_REPRODUCIBLE=""

CHECK_ONLY=0
WRITE_PINS=0
BIN_DIR=""
TEXTURES_DIR="$REPO_ROOT/data/textures"
PIN_FILE="$REPO_ROOT/data/textures.sha256"
KEEP_TEMP=0

while [ $# -gt 0 ]; do
    case "$1" in
        --check)        CHECK_ONLY=1; shift ;;
        --write-pins)   WRITE_PINS=1; shift ;;
        --bin-dir)      BIN_DIR="$2"; shift 2 ;;
        --textures-dir) TEXTURES_DIR="$2"; shift 2 ;;
        --pin-file)     PIN_FILE="$2"; shift 2 ;;
        --keep-temp)    KEEP_TEMP=1; shift ;;
        -h|--help)      sed -n '2,46p' "${BASH_SOURCE[0]}"; exit 0 ;;
        *) echo "build_textures.sh: unknown argument '$1'" >&2; exit 2 ;;
    esac
done

if [ ! -d "$TEXTURES_DIR" ]; then
    echo "ERROR: $TEXTURES_DIR does not exist" >&2
    exit 3
fi

# ── --write-pins needs no tool ──────────────────────────────────────────────
if [ "$WRITE_PINS" -eq 1 ]; then
    HDR="$(mktemp)"
    awk '/^#/ {print; next} {exit}' "$PIN_FILE" > "$HDR" 2>/dev/null || true
    NEW="$(mktemp)"
    cat "$HDR" > "$NEW"
    ( cd "$TEXTURES_DIR" && sha256sum $(ls) ) >> "$NEW"
    mv -f "$NEW" "$PIN_FILE"
    rm -f "$HDR"
    echo "rewrote $PIN_FILE from $TEXTURES_DIR"
    exit 0
fi

if [ -z "$BIN_DIR" ]; then
    for cand in "$REPO_ROOT/build/bin" "$REPO_ROOT/build-gles2/bin"; do
        if [ -x "$cand/generate_textures" ]; then BIN_DIR="$cand"; break; fi
    done
fi
if [ -z "$BIN_DIR" ] || [ ! -x "$BIN_DIR/generate_textures" ]; then
    echo "ERROR: generate_textures not found. Build it first:" >&2
    echo "       cmake --build $REPO_ROOT/build --target generate_textures" >&2
    exit 3
fi

# T417 (board B300): data/textures/ has a SECOND recipe. The spell sprite
# atlas is lifted from the official client's own SpellEffects/*.tga, so it
# cannot come out of generate_textures (which builds procedurally and links
# no TGA decoder). Both tools write into the same directory and the pin file
# covers the union.
if [ ! -x "$BIN_DIR/spell_sprite_atlas_builder" ]; then
    echo "ERROR: spell_sprite_atlas_builder not found in $BIN_DIR. Build it first:" >&2
    echo "       cmake --build $REPO_ROOT/build --target spell_sprite_atlas_builder" >&2
    exit 3
fi

# T430 (board B376): a THIRD recipe. The item icon sheets are lifted from the
# official client's uifiles/default/dragitem*.tga, so like the spell sprites
# they cannot come out of generate_textures. All three tools write into the
# same directory and the pin file covers the union.
if [ ! -x "$BIN_DIR/item_icon_atlas_builder" ]; then
    echo "ERROR: item_icon_atlas_builder not found in $BIN_DIR. Build it first:" >&2
    echo "       cmake --build $REPO_ROOT/build --target item_icon_atlas_builder" >&2
    exit 3
fi

# B1077 (GitLab #397): a FOURTH recipe. The spell icon sheets are lifted from
# the official client's uifiles/default/gemicons*.tga, Spells*.tga and
# Spell_Icons.tga (plus the CW_SpellGemHolder piece of classic_pieces01.tga),
# so like the item icons they cannot come out of generate_textures. All four
# tools write into the same directory and the pin file covers the union.
if [ ! -x "$BIN_DIR/spell_icon_atlas_builder" ]; then
    echo "ERROR: spell_icon_atlas_builder not found in $BIN_DIR. Build it first:" >&2
    echo "       cmake --build $REPO_ROOT/build --target spell_icon_atlas_builder" >&2
    exit 3
fi

# ── In-place regeneration ───────────────────────────────────────────────────
if [ "$CHECK_ONLY" -eq 0 ]; then
    "$BIN_DIR/generate_textures" --output "$TEXTURES_DIR" || exit 4
    "$BIN_DIR/spell_sprite_atlas_builder" --output "$TEXTURES_DIR" || exit 4
    "$BIN_DIR/item_icon_atlas_builder" --output "$TEXTURES_DIR" || exit 4
    "$BIN_DIR/spell_icon_atlas_builder" --output "$TEXTURES_DIR" || exit 4
    echo
    echo "NOTE: data/textures/ was rewritten. Update $PIN_FILE"
    echo "      (scripts/build_textures.sh --write-pins) and rebuild the pack"
    echo "      (scripts/build_willeq_pack.sh) in the SAME commit, or"
    echo "      TexturesReproducible and PackReproducible will both fail."
    exit 0
fi

# ── --check ─────────────────────────────────────────────────────────────────
WORK="$(mktemp -d "${TMPDIR:-/tmp}/willeq_textures.XXXXXXXX")"
cleanup() {
    if [ "$KEEP_TEMP" -eq 1 ]; then echo "  (temp kept at $WORK)"; else rm -rf "$WORK"; fi
}
trap cleanup EXIT

rc=0

# --- assertion 1: PIN -------------------------------------------------------
if [ ! -f "$PIN_FILE" ]; then
    echo "FAIL[PIN]: no pin file at $PIN_FILE" >&2
    exit 1
fi
grep -v '^#' "$PIN_FILE" | grep -v '^[[:space:]]*$' > "$WORK/pins.txt"
PIN_COUNT="$(wc -l < "$WORK/pins.txt")"
awk '{print $2}' "$WORK/pins.txt" | sort > "$WORK/pinned_names.txt"
( cd "$TEXTURES_DIR" && ls ) | sort > "$WORK/tree_names.txt"

if ! diff -u "$WORK/pinned_names.txt" "$WORK/tree_names.txt" > "$WORK/names.diff"; then
    echo "FAIL[PIN]: $TEXTURES_DIR does not hold exactly the pinned set" >&2
    echo "           (- = pinned but absent, + = present but unpinned)" >&2
    sed -n '3,$p' "$WORK/names.diff" >&2
    rc=1
fi

if ! ( cd "$TEXTURES_DIR" && sha256sum --quiet -c "$WORK/pins.txt" ) > "$WORK/pin.log" 2>&1; then
    echo "FAIL[PIN]: a shipped BMP does not match its pinned sha256." >&2
    echo "           Either it was hand-edited, or a generator change was" >&2
    echo "           applied without updating $PIN_FILE in the same commit." >&2
    grep -v ': OK$' "$WORK/pin.log" | head -20 >&2
    rc=1
fi

# --- regenerate -------------------------------------------------------------
mkdir -p "$WORK/regen"
if ! "$BIN_DIR/generate_textures" --output "$WORK/regen" > "$WORK/gen.log" 2>&1; then
    echo "FAIL: generate_textures failed:" >&2
    cat "$WORK/gen.log" >&2
    exit 4
fi
if ! "$BIN_DIR/spell_sprite_atlas_builder" --output "$WORK/regen" \
        > "$WORK/gen_sprites.log" 2>&1; then
    echo "FAIL: spell_sprite_atlas_builder failed:" >&2
    cat "$WORK/gen_sprites.log" >&2
    exit 4
fi
if ! "$BIN_DIR/item_icon_atlas_builder" --output "$WORK/regen" \
        > "$WORK/gen_icons.log" 2>&1; then
    echo "FAIL: item_icon_atlas_builder failed:" >&2
    cat "$WORK/gen_icons.log" >&2
    exit 4
fi
if ! "$BIN_DIR/spell_icon_atlas_builder" --output "$WORK/regen" \
        > "$WORK/gen_spell_icons.log" 2>&1; then
    echo "FAIL: spell_icon_atlas_builder failed:" >&2
    cat "$WORK/gen_spell_icons.log" >&2
    exit 4
fi

# --- assertion 3: CENSUS ----------------------------------------------------
( cd "$WORK/regen" && ls ) | sort > "$WORK/regen_names.txt"
if ! diff -u "$WORK/pinned_names.txt" "$WORK/regen_names.txt" > "$WORK/census.diff"; then
    echo "FAIL[CENSUS]: the texture recipes did not write exactly the pinned set" >&2
    echo "              (- = pinned but not generated, + = generated but unpinned)" >&2
    sed -n '3,$p' "$WORK/census.diff" >&2
    rc=1
fi

# --- assertion 2: RECIPE ----------------------------------------------------
matched=0
exempt=0
drifted=0
while read -r _sha name; do
    [ -f "$WORK/regen/$name" ] || continue
    skip=0
    for e in $NOT_REPRODUCIBLE; do
        if [ "$e" = "$name" ]; then skip=1; break; fi
    done
    if [ "$skip" -eq 1 ]; then
        exempt=$((exempt + 1))
        continue
    fi
    a="$(sha256sum "$TEXTURES_DIR/$name" | awk '{print $1}')"
    b="$(sha256sum "$WORK/regen/$name" | awk '{print $1}')"
    if [ "$a" = "$b" ]; then
        matched=$((matched + 1))
    else
        drifted=$((drifted + 1))
        echo "FAIL[RECIPE]: $name  shipped=$a  regenerated=$b" >&2
        rc=1
    fi
done < "$WORK/pins.txt"

echo "pinned:      $PIN_COUNT files ($PIN_FILE)"
echo "regenerated: $matched byte-identical, $drifted drifted, $exempt exempt (NOT_REPRODUCIBLE)"

if [ "$rc" -eq 0 ]; then
    echo "PASS: data/textures/ matches its pins and its generators."
else
    echo "See scripts/build_textures.sh for what each assertion means." >&2
fi
exit "$rc"
