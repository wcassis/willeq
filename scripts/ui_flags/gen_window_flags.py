#!/usr/bin/env python3
# B1002 (#322): generate the committed snapshot of the official client's
# per-window Style_Transparent flags from the 120 EQUI_*.xml files.
#
# The snapshot is what the ctest pins the committed C++ table against. The
# generator is the RECIPE (run it when the oracle package's XMLs change); the
# output (official_window_flags.tsv) is committed. The XMLs themselves are
# NEVER committed (client files).
#
# Semantics (file-level, per Will's ruling on #322): a window is TRANSLUCENT
# when ANY element in its file sets <Style_Transparent>true. This is what
# "34 translucent / 86 opaque" counts.
import glob
import os
import sys

src = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/eq-oracle/client/uifiles/default_old")
out = sys.argv[2] if len(sys.argv) > 2 else "official_window_flags.tsv"

rows = []
for path in sorted(glob.glob(os.path.join(src, "EQUI_*.xml"))):
    name = os.path.basename(path)[:-4]  # EQUI_X
    with open(path, "rb") as f:
        data = f.read()
    flag = 1 if b"Style_Transparent>true" in data else 0
    rows.append((name, flag))

rows.sort()
with open(out, "w") as f:
    f.write("# B1002: official client per-window Style_Transparent flags (file-level).\n")
    f.write("# Generated by scripts/ui_flags/gen_window_flags.py from %s\n" % src)
    f.write("# 120 official windows; a window is translucent when ANY element sets\n")
    f.write("# <Style_Transparent>true. Column 2: 1=translucent, 0=opaque.\n")
    f.write("# official_name\ttransparent\n")
    for name, flag in rows:
        f.write("%s\t%d\n" % (name, flag))

n_t = sum(flag for _, flag in rows)
print("files=%d translucent=%d opaque=%d -> %s" % (len(rows), n_t, len(rows) - n_t, out))
