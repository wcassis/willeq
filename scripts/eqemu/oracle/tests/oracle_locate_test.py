#!/usr/bin/env python3
"""B1058 (#378): the template library against the archived oracle corpus.

For every row of locate_corpus.tsv (expected centres measured by text bbox /
title-bar colour run, NOT by template matching; generated by
review/B1058/tools/build_library.py):

  pos  the template's best match scores >= its manifest min_score and lands
       within 1 px of an expected centre;
  neg  the best match anywhere in the frame scores < min_score.

Every template's min_score must be the midpoint of the gap between its
highest negative and lowest positive score (both paths), so a threshold is
derived, never typed. With cv2 importable (and ORACLE_LOCATE_FORCE_NUMPY
unset) both paths run and must agree to 1e-3 at the peak and on the location;
ORACLE_LOCATE_FORCE_NUMPY=1 runs the numpy path alone.

The corpus is evidence outside the repo (review/B1058/corpus, override with
ORACLE_LOCATE_CORPUS). Exit 125 (ctest SKIP) when it or NumPy/Pillow is
absent -- the CI runners have neither (measured, review/B1058/README.md);
every frame's sha256 is pinned in locate_corpus.tsv, so a drifted corpus
fails instead of passing on different bytes.

  --report FILE           write the per-template score table (README)
  --write-thresholds      set manifest min_score from the measured gaps
"""
import argparse
import hashlib
import os
import sys
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ORACLE = os.path.dirname(HERE)
sys.path.insert(0, ORACLE)
TEMPLATES = os.path.join(ORACLE, "templates")
CORPUS_TSV = os.path.join(HERE, "locate_corpus.tsv")
DEFAULT_CORPUS = "/mnt/projects/fable/review/B1058/corpus"
AGREE = 1e-3


def skip(msg):
    print(f"SKIP: {msg}")
    sys.exit(125)


def read_rows():
    rows = []
    with open(CORPUS_TSV, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#") or line.startswith("template\t"):
                continue
            t, frame, sha, kind, expect, how = line.rstrip("\n").split("\t")
            pts = [] if expect == "-" else [tuple(map(int, p.split(","))) for p in expect.split(";")]
            rows.append({"template": t, "frame": frame, "sha": sha, "kind": kind,
                         "expect": pts, "how": how})
    return rows


def score_frame(args):
    """Locate every template in one frame on every path; keep peaks only."""
    corpus, frame, names, paths = args
    import oracle_locate as ol
    img = ol.load_luma(os.path.join(corpus, frame))
    cache = ol.NumpyFrame(img)
    res = {}
    for name in names:
        tpl = ol.load_luma(os.path.join(TEMPLATES, name + ".png"))
        h, w = tpl.shape
        rec, maps = {}, {}
        for path in paths:
            r = ol.locate_arrays(img, tpl, path=path,
                                 cache=cache if path == "numpy" else None, want_map=True)
            rec[path] = (r["cx"], r["cy"], r["score"])
            rec["second_" + path] = r["second"]
            maps[path] = r["map"]
        if "cv2" in paths:
            # both maps compared at both paths' peaks (map index = top-left)
            rec["agree"] = max(abs(float(maps["cv2"][cy - h // 2, cx - w // 2]) -
                                   float(maps["numpy"][cy - h // 2, cx - w // 2]))
                               for cx, cy, _ in (rec["cv2"], rec["numpy"]))
        res[name] = rec
    return frame, res


_SHAPES = {}


def tpl_shape(name):
    if name not in _SHAPES:
        from PIL import Image
        with Image.open(os.path.join(TEMPLATES, name + ".png")) as im:
            _SHAPES[name] = (im.height, im.width)
    return _SHAPES[name]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report")
    ap.add_argument("--write-thresholds", action="store_true")
    ap.add_argument("--jobs", type=int, default=min(8, os.cpu_count() or 1))
    a = ap.parse_args()
    try:
        import numpy  # noqa: F401
        from PIL import Image  # noqa: F401
    except ImportError as exc:
        skip(f"{exc}: the locator needs NumPy + Pillow on the driver host")
    corpus = os.environ.get("ORACLE_LOCATE_CORPUS", DEFAULT_CORPUS)
    if not os.path.isdir(corpus):
        skip(f"corpus {corpus} not present on this host")
    import oracle_locate as ol
    paths = ["numpy"] + (["cv2"] if ol.have_cv2() else [])
    print(f"paths: {' + '.join(paths)}"
          f"{' (ORACLE_LOCATE_FORCE_NUMPY=1)' if os.environ.get('ORACLE_LOCATE_FORCE_NUMPY') == '1' else ''}")

    failures = []
    manifest = ol.read_manifest(TEMPLATES)
    rows = read_rows()
    names = sorted({r["template"] for r in rows})
    for name in names:
        if name not in manifest:
            failures.append(f"{name}: in locate_corpus.tsv but not in manifest.tsv")
            continue
        m = manifest[name]
        f = os.path.join(TEMPLATES, m["file"])
        if ol.sha256_file(f) != m["template_sha256"]:
            failures.append(f"{name}: template bytes differ from manifest template_sha256")
        if os.path.exists(m["source"]) and ol.sha256_file(m["source"]) != m["source_sha256"]:
            failures.append(f"{name}: source {m['source']} differs from manifest source_sha256")
    for name in manifest:
        if name not in names:
            failures.append(f"{name}: in manifest.tsv but has no corpus rows")
    frames = sorted({r["frame"] for r in rows})
    for fr in frames:
        sha = {r["sha"] for r in rows if r["frame"] == fr}
        with open(os.path.join(corpus, fr), "rb") as fh:
            if hashlib.sha256(fh.read()).hexdigest() not in sha:
                failures.append(f"{fr}: corpus frame bytes differ from the pinned sha256")
    if failures:
        print("\n".join("FAIL: " + f for f in failures))
        return 1

    jobs = [(corpus, fr, names, paths) for fr in frames]
    scores = {}
    with ProcessPoolExecutor(max_workers=a.jobs) as ex:
        for fr, res in ex.map(score_frame, jobs):
            scores[fr] = res

    table = []
    new_thresholds = {}
    for name in names:
        pos = [r for r in rows if r["template"] == name and r["kind"] == "pos"]
        neg = [r for r in rows if r["template"] == name and r["kind"] == "neg"]
        pos_s = [min(scores[r["frame"]][name][p][2] for p in paths) for r in pos]
        neg_s = [max(scores[r["frame"]][name][p][2] for p in paths) for r in neg]
        lo_pos = min(pos_s) if pos_s else None
        hi_neg = max(neg_s) if neg_s else None
        if lo_pos is not None and hi_neg is not None and lo_pos > hi_neg:
            mid = round((lo_pos + hi_neg) / 2, 4)
        else:
            mid = None
        new_thresholds[name] = mid
        table.append((name, pos_s, neg_s, mid))
        cur = manifest[name]["min_score"]
        if not a.write_thresholds:
            if mid is None:
                if cur != "rejected":
                    failures.append(f"{name}: no positive/negative gap but manifest min_score={cur}")
                continue
            if cur in ("-", "rejected") or abs(float(cur) - mid) > 5e-5:
                failures.append(f"{name}: manifest min_score {cur} is not the gap midpoint {mid:.4f}")
                continue
            thr = float(cur)
            for r, s in zip(pos, pos_s):
                for p in paths:
                    cx, cy, sc = scores[r["frame"]][name][p]
                    if sc < thr:
                        failures.append(f"{name} {p}: positive {r['frame']} scored {sc:.4f} < {thr}")
                    if not any(abs(cx - ex) <= 1 and abs(cy - ey) <= 1 for ex, ey in r["expect"]):
                        failures.append(f"{name} {p}: positive {r['frame']} located at {cx},{cy}, "
                                        f"expected {r['expect']} (+/- 1 px)")
            for r in neg:
                for p in paths:
                    sc = scores[r["frame"]][name][p][2]
                    if sc >= thr:
                        failures.append(f"{name} {p}: negative {r['frame']} scored {sc:.4f} >= {thr}")
        if "cv2" in paths:
            for r in pos + neg:
                rec = scores[r["frame"]][name]
                if rec["agree"] >= AGREE:
                    failures.append(f"{name}: cv2/numpy differ by {rec['agree']:.2e} on {r['frame']}")
                (cx1, cy1, s1), (cx2, cy2, s2) = rec["cv2"], rec["numpy"]
                if abs(s1 - s2) >= AGREE:
                    failures.append(f"{name}: peak scores cv2 {s1:.5f} numpy {s2:.5f} on {r['frame']}")
                if (cx1, cy1) != (cx2, cy2) and abs(s1 - s2) >= AGREE:
                    failures.append(f"{name}: peaks at {cx1},{cy1} vs {cx2},{cy2} on {r['frame']}")

    if a.write_thresholds:
        for name, mid in new_thresholds.items():
            manifest[name]["min_score"] = "rejected" if mid is None else f"{mid:.4f}"
        ol.write_manifest(manifest, TEMPLATES)
        print(f"wrote min_score for {len(new_thresholds)} templates")
    if a.report:
        import numpy as np
        with open(a.report, "w") as fh:
            fh.write(f"paths: {' + '.join(paths)}; scores are the worse of the paths "
                     "(lowest for positives, highest for negatives)\n\n")
            fh.write("| template | n pos | pos min | pos median | n neg | neg max | neg median | "
                     "gap | min_score | runner-up on positives (max) | max cv2/numpy diff |\n"
                     "|---|---|---|---|---|---|---|---|---|---|---|\n")
            for name, pos_s, neg_s, mid in table:
                agree = "-"
                if "cv2" in paths:
                    agree = "%.1e" % max(scores[r["frame"]][name]["agree"]
                                         for r in rows if r["template"] == name and r["kind"] != "skip")
                sec = [scores[r["frame"]][name]["second_" + p] for r in rows
                       if r["template"] == name and r["kind"] == "pos" for p in paths]
                sec = [v for v in sec if v is not None]
                fh.write("| %s | %d | %s | %s | %d | %s | %s | %s | %s | %s | %s |\n" % (
                    name, len(pos_s), "%.4f" % min(pos_s) if pos_s else "-",
                    "%.4f" % np.median(pos_s) if pos_s else "-", len(neg_s),
                    "%.4f" % max(neg_s) if neg_s else "-", "%.4f" % np.median(neg_s) if neg_s else "-",
                    "%.4f" % (min(pos_s) - max(neg_s)) if pos_s and neg_s else "-",
                    "rejected" if mid is None else "%.4f" % mid,
                    "%.4f" % max(sec) if sec else "-", agree))
            fh.write("\nHistograms (count per 0.05 bin, bins 0.00 .. 1.00; P = positives, N = negatives):\n\n```\n")
            edges = np.linspace(0, 1, 21)
            for name, pos_s, neg_s, mid in table:
                hp = np.histogram(np.clip(pos_s, 0, 1), edges)[0]
                hn = np.histogram(np.clip(neg_s, 0, 1), edges)[0]
                fh.write(f"{name:24s} P {' '.join('%2d' % v for v in hp)}\n")
                fh.write(f"{'':24s} N {' '.join('%2d' % v for v in hn)}\n")
            fh.write("```\n")
    n_pos = sum(1 for r in rows if r["kind"] == "pos")
    n_neg = sum(1 for r in rows if r["kind"] == "neg")
    if failures:
        print("\n".join("FAIL: " + f for f in failures[:200]))
        print(f"{len(failures)} failure(s)")
        return 1
    print(f"PASS: {len(names)} templates, {len(frames)} frames, {n_pos} positive and {n_neg} "
          f"negative rows on {' + '.join(paths)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
