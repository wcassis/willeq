#!/bin/bash
# T498 (board B755): export the server's items.id/name/idfile to a committed TSV
# so a ctest test can compare data/item_models.json against it with NO live
# mariadb.
#
# `idfile` is what the server turns into a weapon's appearance material:
#   Mob::GetEquipmentMaterial() -> atoi(&item->IDFile[2])
#   (/mnt/projects/akk-stack/code/zone/mob_appearance.cpp)
# so the numeric part of IT<n> is the number every render site ultimately wants.
#
# Takes the eqemu lock (exit 64 = someone else holds it) and releases it on
# every path. Needs only the mariadb container.
#
# Usage: scripts/eqemu/export_item_idfile.sh [-o data/item_idfile.tsv]

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
source "${SCRIPT_DIR}/env.sh"

OUT="${REPO_ROOT}/data/item_idfile.tsv"
UNIT="T498"
while [ $# -gt 0 ]; do
    case "$1" in
        -o|--out)  OUT="$2"; shift 2 ;;
        --unit)    UNIT="$2"; shift 2 ;;
        *) echo "unknown argument: $1" >&2; exit 2 ;;
    esac
done

LOCK_TAKEN=0
cleanup() {
    if [ "${LOCK_TAKEN}" = "1" ]; then
        eqemu_lock_release || true
        echo "eqemu lock released"
    fi
}
trap cleanup EXIT

if ! eqemu_lock_take "${UNIT}"; then
    echo "eqemu lock is held by: $(eqemu_lock_show)" >&2
    exit 64
fi
LOCK_TAKEN=1
echo "eqemu lock taken as ${UNIT}"

ROWS=$(mysql_exec "SELECT COUNT(*) FROM items" | tail -n1)
echo "items rows: ${ROWS}"

TMP="$(mktemp)"
trap 'rm -f "${TMP}"; cleanup' EXIT
{
    echo "# data/item_idfile.tsv -- generated by scripts/eqemu/export_item_idfile.sh"
    echo "# source_host	${EQEMU_HOST}"
    echo "# database	peq (container ${MARIADB_CONTAINER})"
    echo "# items_rows	${ROWS}"
    echo "# generated_utc	$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# columns	id	name	idfile"
    mysql_exec "SELECT id, name, idfile FROM items ORDER BY id" | tail -n +2
} > "${TMP}"

mkdir -p "$(dirname "${OUT}")"
mv "${TMP}" "${OUT}"
echo "wrote ${OUT} ($(wc -l < "${OUT}") lines)"
