// B875 (issue #219) -- the solver for the OWED one-time fit of the official
// client's Chase camera constants (refactor/B875/FIT_PLAN.md).
//
// Input: MANUAL correspondences (Will's ruling) -- for each official-client
// still, the commanded player pose it was captured at and a set of image
// points hand-picked on static zone geometry, each paired with that
// geometry's world position read from the zone file. Output: the rig that
// explains every still at once -- azimuth, pitch, distance, look-at height,
// horizontal FOV and (with two or more eye heights) the race-scale exponent.
//
// The camera model is fable's rig (camera_rig.h computeCameraRigPose(): the
// look-at on the player's axis `height` above the feet, the camera `distance`
// back along -(sin a, cos a) with a = heading + azimuth, raised by `pitch`),
// with the rig scaled by (eye / refEye)^eyeScaleExponent -- exponent 1 is
// fable's current law (scaleChaseRigForEye()), 0 is "no race scaling". The
// projection is a square-pixel pinhole centred on the image, world Z up,
// no roll. tests/test_chase_rig_fit.cpp pins this model against the
// production computeCameraRigPose().
//
// CIRCULARITY GUARDS (the MR !31 failure, refactor/B875/README.md):
//   - checkInputs() refuses image points that are not on the 0.5 px grid a
//     person clicking pixels produces. Points generated by projecting 3D
//     geometry through a camera land off that grid.
//   - fitChaseRig() refuses a fit whose RMS residual is below kMinPlausibleRmsPx:
//     hand-picked points cannot reach it, generated ones do.
//   - The solver never defaults its start to kChaseRig; the caller passes a
//     start, and the tests prove the result does not depend on it.
// No arithmetic can tell a clicked point from a projected one that was then
// ROUNDED to the grid; that case is closed by the procedure in FIT_PLAN.md
// (per-still provenance and an independent re-click audit), not by this code.

#pragma once

#include <string>
#include <vector>

namespace chase_fit {

// The fitted parameters. Angles in degrees, lengths in EQ units.
struct RigParams {
    double azimuthDeg = 0.0;
    double pitchDeg = 0.0;
    double distance = 0.0;
    double height = 0.0;
    double hfovDeg = 0.0;
    double eyeScaleExponent = 1.0;
};

// One still: the commanded pose (client-internal EQ frame, Z up; heading in
// EQ 0-512 units), the character's eye above its feet, the image size, and
// the still's file name (provenance; never empty).
struct CapturePose {
    std::string still;
    int width = 0;
    int height = 0;
    double playerX = 0.0, playerY = 0.0, feetZ = 0.0;
    double headingEq512 = 0.0;
    double eyeAboveFeet = 0.0;
};

// One correspondence: a world point on static geometry and the pixel it was
// picked at (origin at the image's top-left corner, so pixel (i, j)'s centre
// is (i + 0.5, j + 0.5)). `geometryRef` names where the world point came from
// (zone, mesh/fragment, vertex) -- never a camera.
struct Correspondence {
    int pose = 0;
    double worldX = 0.0, worldY = 0.0, worldZ = 0.0;
    double u = 0.0, v = 0.0;
    std::string geometryRef;
};

struct FitOptions {
    double refEyeAboveFeet = 6.023;  // the eye at which the rig is unscaled
    bool fitEyeScaleExponent = false;
    int maxIterations = 200;
};

struct FitResult {
    RigParams rig;
    double rmsPx = 0.0;
    int iterations = 0;
    bool converged = false;
    // One-sigma parameter uncertainties from the residual covariance, same
    // order as RigParams (0 for a parameter that was not fitted).
    double sigma[6] = {0, 0, 0, 0, 0, 0};
    // Every reason the fit must not be used. Empty == usable.
    std::vector<std::string> refusals;
    bool usable() const { return refusals.empty(); }
};

// Acceptance numbers (FIT_PLAN.md "Acceptance").
constexpr int kMinPoses = 5;
constexpr int kMinDistinctHeadings = 3;
constexpr int kMinPointsPerPose = 8;
constexpr double kMinPlausibleRmsPx = 0.1;   // below this the points were not clicked
constexpr double kMaxAcceptedRmsPx = 2.0;    // above this the model does not explain the stills

// The camera pose for a rig at a capture (EQ frame).
void cameraPose(const RigParams& rig, const CapturePose& pose, double refEye,
                double cam[3], double target[3]);

// Project a world point; false when it is behind the camera.
bool projectPoint(const RigParams& rig, const CapturePose& pose, double refEye,
                  double wx, double wy, double wz, double& u, double& v);

// RMS reprojection error of a rig over every correspondence, pixels.
double rmsResidualPx(const RigParams& rig, const std::vector<CapturePose>& poses,
                     const std::vector<Correspondence>& points, double refEye);

// Input refusals (too few stills/headings/points, missing provenance, a
// pixel off the click grid, a point outside its image, an unknown pose).
std::vector<std::string> checkInputs(const std::vector<CapturePose>& poses,
                                     const std::vector<Correspondence>& points,
                                     const FitOptions& options);

// Levenberg-Marquardt from `start`. Always returns the solution it reached;
// `refusals` says whether it may be used.
FitResult fitChaseRig(const std::vector<CapturePose>& poses,
                      const std::vector<Correspondence>& points, const RigParams& start,
                      const FitOptions& options);

// Does a GIVEN rig explain the stills? (The check a later unit runs against
// fable's constants once the fit exists.) True iff its RMS is within
// kMaxAcceptedRmsPx.
bool rigExplainsStills(const RigParams& rig, const std::vector<CapturePose>& poses,
                       const std::vector<Correspondence>& points, double refEye,
                       double* rmsOut = nullptr);

// Parse the correspondence TSV (format in FIT_PLAN.md). Returns false and
// fills `error` on a malformed file.
bool readCorrespondenceTsv(const std::string& path, std::vector<CapturePose>& poses,
                           std::vector<Correspondence>& points, std::string& error);

}  // namespace chase_fit
