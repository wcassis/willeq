// T504b: model_fingerprint -- the regression net for entity source pruning.
//
// Headless (EDT_NULL, no server, no DISPLAY). For every race x gender in
// data/willeq.db that resolves to a model in ONE zone's archive context, it
// prints one line of MODEL DATA fingerprints through the production
// RaceModelLoader (getRaceModelData), plus the same for the variant built
// with body=1/head=1 (the WearChange path, getVariantModelData):
//
//   race=<id> gender=<g> variant=<b>,<h> code=<modelCode> verts=<n> tris=<n>
//   geom=<fnv of raw vertices+triangles> bones=<n> skel=<fnv of bone
//   names+parents> anims=<sorted codes> xf=<fnv of every bone's transform at
//   frames 0/mid/last of l01,c01,o01,p01 where present>
//
// A golden is this output generated by the code BEFORE a pruning leg; any
// diff afterwards is a failure (byte-identical model data), never a
// judgement call. Run once per zone context (separate processes -- the
// loader's caches are per process).
//
//   model_fingerprint --zone <name> [--eq <client dir>] [--db <willeq.db>]
//                     [--max-race <n>] [--out <file>]
#include <irrlicht.h>

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <memory>
#include <string>
#include <utility>
#include <vector>

#include "client/graphics/constrained_renderer_config.h"
#include "client/graphics/constrained_texture_cache.h"
#include "client/graphics/eq/race_model_loader.h"
#include "client/willeq_database.h"
#include "common/logging.h"
#include "common/willeq_paths.h"  // EQ_CLIENT_DATA_PATH + WILLEQ_DB_REAL_PATH at run time (B1090)

namespace {

uint64_t fnv1a(const void* data, size_t n, uint64_t h = 1469598103934665603ull) {
    const unsigned char* p = static_cast<const unsigned char*>(data);
    for (size_t i = 0; i < n; ++i) { h ^= p[i]; h *= 1099511628211ull; }
    return h;
}
uint64_t fnvStr(const std::string& s, uint64_t h) { return fnv1a(s.data(), s.size(), h); }

std::string fingerprint(const EQT::Graphics::RaceModelData& m) {
    using namespace EQT::Graphics;
    std::string out;
    const ZoneGeometry* g = m.rawGeometry ? m.rawGeometry.get() : m.combinedGeometry.get();
    size_t verts = 0, tris = 0;
    uint64_t geom = 1469598103934665603ull;
    if (g) {
        verts = g->vertices.size();
        tris = g->triangles.size();
        if (!g->vertices.empty()) geom = fnv1a(g->vertices.data(), verts * sizeof(Vertex3D), geom);
        if (!g->triangles.empty()) geom = fnv1a(g->triangles.data(), tris * sizeof(Triangle), geom);
    }
    std::string code = m.skeleton ? m.skeleton->modelCode : m.raceName;
    size_t bones = 0;
    uint64_t skel = 1469598103934665603ull;
    std::vector<std::string> anims;
    uint64_t xf = 1469598103934665603ull;
    if (m.skeleton) {
        bones = m.skeleton->bones.size();
        for (const auto& b : m.skeleton->bones) {
            skel = fnvStr(b.name, skel);
            skel = fnv1a(&b.parentIndex, sizeof(b.parentIndex), skel);
        }
        for (const auto& [c, a] : m.skeleton->animations) if (a) anims.push_back(c);
        std::sort(anims.begin(), anims.end());
        static const char* kCodes[] = {"l01", "c01", "o01", "p01"};
        for (const char* c : kCodes) {
            for (const auto& b : m.skeleton->bones) {
                auto it = b.animationTracks.find(c);
                if (it == b.animationTracks.end() || !it->second) continue;
                const auto& frames = it->second->frames;
                if (frames.empty()) continue;
                const size_t idx[3] = {0, frames.size() / 2, frames.size() - 1};
                for (size_t k : idx) xf = fnv1a(&frames[k], sizeof(BoneTransform), xf);
            }
        }
    }
    std::string animList;
    for (const auto& a : anims) { if (!animList.empty()) animList += ','; animList += a; }
    char buf[256];
    std::snprintf(buf, sizeof(buf), "code=%s verts=%zu tris=%zu geom=%016llx bones=%zu skel=%016llx anims=",
                  code.c_str(), verts, tris, static_cast<unsigned long long>(geom), bones,
                  static_cast<unsigned long long>(skel));
    out += buf;
    out += animList.empty() ? "-" : animList;
    std::snprintf(buf, sizeof(buf), " xf=%016llx", static_cast<unsigned long long>(xf));
    out += buf;
    return out;
}

} // namespace

int main(int argc, char** argv) {
    std::string zone, eq = EQ_CLIENT_DATA_PATH, db = WILLEQ_DB_REAL_PATH, outPath, logLevel = "ERROR";
    int maxRace = 700;
    int onlyRace = 0;
    bool variantFirst = false;
    for (int i = 1; i < argc; ++i) {
        std::string a = argv[i];
        auto next = [&](std::string& dst) { if (i + 1 < argc) dst = argv[++i]; };
        if (a == "--zone") next(zone);
        else if (a == "--eq") next(eq);
        else if (a == "--db") next(db);
        else if (a == "--out") next(outPath);
        else if (a == "--max-race") { std::string v; next(v); maxRace = std::atoi(v.c_str()); }
        else if (a == "--only-race") { std::string v; next(v); onlyRace = std::atoi(v.c_str()); }
        else if (a == "--variant-first") variantFirst = true;
        else if (a == "--log") next(logLevel);
        else { std::fprintf(stderr, "unknown arg %s\n", a.c_str()); return 2; }
    }
    if (zone.empty()) { std::fprintf(stderr, "usage: model_fingerprint --zone <name> [--eq dir] [--db file] [--out file]\n"); return 2; }
    if (!eq.empty() && eq.back() != '/') eq += '/';
    SetLogLevel(logLevel == "INFO" ? LOG_INFO : logLevel == "DEBUG" ? LOG_DEBUG : logLevel == "WARN" ? LOG_WARN : LOG_ERROR);

    EQT::WilleqDatabase database;
    if (!database.open(db)) { std::fprintf(stderr, "cannot open db %s\n", db.c_str()); return 3; }
    EQT::WilleqDatabase::setGlobalInstance(&database);

    irr::SIrrlichtCreationParameters params;
    params.DriverType = irr::video::EDT_NULL;
    params.WindowSize = irr::core::dimension2d<irr::u32>(64, 64);
    irr::IrrlichtDevice* device = irr::createDeviceEx(params);
    if (!device) { std::fprintf(stderr, "no EDT_NULL device\n"); return 3; }

    auto loader = std::make_unique<EQT::Graphics::RaceModelLoader>(
        device->getSceneManager(), device->getVideoDriver(), device->getFileSystem());
    auto config = EQT::Graphics::ConstrainedRendererConfig::fromPreset(
        EQT::Graphics::ConstrainedRenderingPreset::TNT);
    auto texCache = std::make_unique<EQT::Graphics::ConstrainedTextureCache>(config);
    texCache->setDriver(device->getVideoDriver());
    loader->setConstrainedTextureCache(texCache.get());
    loader->getMeshBuilder()->setConstrainedTextureCache(texCache.get());
    loader->setClientPath(eq);
    // The client's own order (EntityRenderer): globals first, then the zone.
    loader->loadGlobalModels();
    loader->loadNumberedGlobalModels();
    loader->setCurrentZone(zone);
    loader->loadZoneModels(zone);

    // Keep model data alive until every preload has finished mutating any
    // shared skeleton. Fingerprinting while building makes the result depend
    // on which race/variant happened to load first.
    std::vector<std::pair<std::string, std::shared_ptr<EQT::Graphics::RaceModelData>>> rows;
    for (int race = 1; race <= maxRace; ++race) {
        if (onlyRace != 0 && race != onlyRace) continue;
        const auto info = database.getRaceModel(static_cast<uint16_t>(race));
        if (!info.found) continue;
        for (uint8_t gender = 0; gender < 2; ++gender) {
            const auto rid = static_cast<uint16_t>(race);
            // ensureModelDataLoaded is the client's synchronous build path
            // (getRaceModelData only reads what is already built).
            if (variantFirst) loader->preloadVariantModel(rid, gender, 1, 1);
            auto base = loader->ensureModelDataLoaded(rid, gender);
            char head[64];
            std::snprintf(head, sizeof(head), "race=%d gender=%d variant=0,0 ", race, gender);
            rows.emplace_back(head, base);
            if (!base) continue;
            if (!variantFirst) loader->preloadVariantModel(rid, gender, 1, 1);
            auto var = loader->getVariantModelData(rid, gender, 1, 1);
            std::snprintf(head, sizeof(head), "race=%d gender=%d variant=1,1 ", race, gender);
            rows.emplace_back(head, var);
        }
    }
    std::vector<std::string> lines;
    lines.reserve(rows.size());
    for (const auto& [head, data] : rows)
        lines.push_back(head + (data ? fingerprint(*data) : "none"));
    std::sort(lines.begin(), lines.end());
    std::string text = "# model_fingerprint zone=" + zone + "\n";
    for (const auto& l : lines) text += l + "\n";
    if (outPath.empty()) std::fputs(text.c_str(), stdout);
    else { std::ofstream f(outPath); f << text; }
    loader.reset();
    texCache.reset();
    device->drop();
    EQT::WilleqDatabase::setGlobalInstance(nullptr);
    return 0;
}
