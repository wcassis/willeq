// The renderer still names the record from the vocabulary's spellAnim, not
// from its spellAffectIndex (the bridge payload carries both, B1127) -- and
// B1153 retired the rows that number used to select, so it identifies the
// spellsnew.edd emitters that draw the spell (B1149-B1152).
TEST_F(AnimRows, SpellVisualFxNamesTheFieldOneFortyFiveRecord) {
    irr::SIrrlichtCreationParameters p;
    p.DriverType = irr::video::EDT_NULL;
    irr::IrrlichtDevice* device = irr::createDeviceEx(p);
    if (!device) GTEST_SKIP() << "Failed to create EDT_NULL Irrlicht device";
    {
        EQ::SpellVisualFX fx(device->getSceneManager(), device->getVideoDriver(), std::string());
        auto note = [&](uint32_t spell, int16_t f123, int16_t f145) {
            EQ::SpellVisualVocabulary v;
            v.known = true;
            v.school = EQ::SpellSchool::Evocation;
            v.spellAffectIndex = f123;
            v.spellAnim = f145;
            fx.noteSpellVocabulary(spell, v);
        };
        note(1656, 25, 85);
        note(14, 25, 115);
        note(1605, 23, 106);
        note(1899, -1, 83);
        note(4499, 51, 326);  // Defensive Discipline: B1134 measured 326 as row 51
        note(8604, 51, 325);  // Leechcurse Discipline: field 123 has a row, field 145 none
        EXPECT_EQ(fx.sourceRecordOf(1656), 85);
        EXPECT_EQ(fx.sourceRecordOf(14), 115);
        EXPECT_EQ(fx.sourceRecordOf(1605), 106);
        EXPECT_EQ(fx.sourceRecordOf(1899), 83);
        EXPECT_EQ(fx.sourceRecordOf(4499), 326);
        EXPECT_EQ(fx.sourceRecordOf(8604), 325);
    }
    device->drop();
}

