// B1137 (#457): a spell is drawn with the row of the record the official
// client DRAWS -- its spellsnew.eff record (spells_us.txt field 145, B1127)
// -- not of its spells.eff record (field 123).
//
// The B1130 survey captured one spell per field-123 record, and those 40
// spells happen to draw 40 different field-145 records, so every measured row
// is a measurement of ONE field-145 record (review/B1137/README.md sec. 4).
//
// B1153 (#473): the rows are RETIRED -- config/spell_effects.json carries
// the DEFAULT rows only (refactor/B1153/README.md), and every record is drawn
// by its spellsnew.eff record's EDD emitters (B1149 population/sprite, B1150
// shape, B1151 motion, B1152 the missile arrival). This file is now the band:
// tests/spell_anim_rows.h maps each measured row to the field-145 record it
// was captured on, and tests/spell_fx_row_oracle.h carries the measured
// anchor classes per row (generated by
// refactor/B1153/scripts/gen_row_bands.py). The runtime assertions below are
// the post-retirement world: it carries no rows, only the defaults.

#include <gtest/gtest.h>

#include "client/graphics/environment/spell_effects_config.h"
#include "spell_anim_rows.h"
#include "spell_fx_row_oracle.h"
#include "spell_pool.h"

