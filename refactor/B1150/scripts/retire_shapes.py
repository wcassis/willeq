#!/usr/bin/env python3
"""B1150 (#470): retire the shape words from config/spell_effects.json.

Every measured sourceRecords row, every targetRecords row and every
spellOverrides shape belongs to a spell with a spellsnew.eff field-145
record, whose +0xA8..+0xD0 words (plus +0x19C) now draw it. This script:
  - strips lo/hi/halfWidth/centroid (+ spiral, disc*) from the source rows,
    leaving {"anchor": ..., "capture": ...} (the anchor stays: the reader
    parses it and the bands pin it; it is evidence, not an input --
    hasShape is derived from the lo/hi/halfWidth membership, so a row
    without them is the default row: the style's own cloud);
  - strips lo/hi/halfWidth/centroid/boneAt from every target row (the
    shaped rows' values were inputs, the body/caster rows' were already
    evidence-only: hasShape is false for anchor body/caster);
  - strips the spellOverrides' spawnShape / spawnExtents lines (the
    styles' own stay: they are the shape of a spell with no record);
  - rewrites the two rule strings to the B1150 split.
The values are preserved in tests/spell_fx_shape_oracle.h (generated by
gen_shape_bands.py over the PRE-retirement config -- run that first).
"""
import re
import json
import sys

PATH = sys.argv[1] if len(sys.argv) > 1 else "config/spell_effects.json"
lines = open(PATH).read().split("\n")

SRC_KEYS = ["lo", "hi", "halfWidth", "centroid", "spiral",
            "discLo", "discHi", "discHalfWidth", "discShare"]
TGT_KEYS = ["lo", "hi", "halfWidth", "centroid", "boneAt"]

def strip_row(line, keys):
    """One record row line: `            "N": {...},` -- drop `keys`, keep
    everything else byte-for-byte (json round-trip of the row object)."""
    m = re.match(r'^(\s*"\d+": )(\{.*\})(,?)\s*$', line)
    if not m:
        return line, False
    obj = json.loads(m.group(2))
    if not any(k in obj for k in keys):
        return line, False
    for k in keys:
        obj.pop(k, None)
    return m.group(1) + json.dumps(obj, separators=(", ", ": ")) + m.group(3), True

section = None
in_records = False
depth = 0
out = []
changed_src = changed_tgt = removed_shape = 0
i = 0
while i < len(lines):
    line = lines[i]
    s = line.strip()

    m = re.match(r'^    "([a-zA-Z]+)": \{', line)
    if m:
        section = m.group(1)
        in_records = False
        out.append(line)
        i += 1
        continue

    if section in ("sourceRecords", "targetRecords") and s == '"records": {':
        in_records = True
        depth = 1
        out.append(line)
        i += 1
        continue
    if in_records:
        if re.match(r'^\s*"\d+": \{', line):
            keys = SRC_KEYS if section == "sourceRecords" else TGT_KEYS
            line, changed = strip_row(line, keys)
            if changed:
                if section == "sourceRecords":
                    changed_src += 1
                else:
                    changed_tgt += 1
        out.append(line)
        depth += line.count("{") - line.count("}")
        if depth <= 0:
            in_records = False
        i += 1
        continue

    # spellOverrides' own shape lines (one key per line) -- ONLY in the
    # spellOverrides section: the styles' own spawnShape/spawnExtents (the
    # shape of a spell with no record) stay.
    if section == "spellOverrides" and (
        re.match(r'^"spawnShape": "[A-Z]+",$', s) or re.match(r'^"spawnExtents": \[', s)
    ):
        removed_shape += 1
        i += 1
        continue

    out.append(line)
    i += 1

text = "\n".join(out)
json.loads(text)  # must stay valid JSON

text = text.replace(
    " B1149 (#469): a row gives its record's Source SHAPE only -- populations, "
    "sprite sizes, lifetimes, colour and alpha are each slot's spellsnew.edd "
    "emitter's (the rows' measured coverages are tests/spell_fx_population_oracle.h); "
    "a spellOverrides castGlow/castSpray that sets spawnShape keeps its own geometry. "
    "Rows: review/B1131/scripts/gen_source_records.py.",
    " B1150 (#470): a row carries NO shape any more -- every row's spell has a "
    "spellsnew.eff field-145 record, whose +0xA8 shape with dims +0xAC/+0xB0/+0xB4, "
    "offsets +0xB8/+0xBC/+0xC0, tilts +0xC4/+0xC8, depth bias +0xD0 and +0x19C scale "
    "draws the record's Source (the retired lo/hi/halfWidth/centroid + disc words are "
    "the bands in tests/spell_fx_shape_oracle.h, generated by "
    "refactor/B1150/scripts/gen_shape_bands.py); populations, sprite sizes, "
    "lifetimes, colour and alpha are each slot's spellsnew.edd emitter's (the rows' "
    "measured coverages are tests/spell_fx_population_oracle.h); the anchor and "
    "capture stay as evidence (hasShape is derived from the shape keys' absence, so "
    "a row without them is the default row: the style's own cloud). Rows: "
    "review/B1131/scripts/gen_source_records.py.",
)
assert "B1150 (#470): a row carries NO shape" in text
text = text.replace(
    "the rows carry no onset or end (their measured values are tests/spell_fx_timing_oracle.h)\"",
    "the rows carry no onset or end (their measured values are tests/spell_fx_timing_oracle.h); "
    "B1150 (#470): no shape either -- every row's spell has a field-145 record, "
    "whose +0xA8..+0xD0 words draw the landing (the retired lo/hi/halfWidth/centroid "
    "bands: tests/spell_fx_shape_oracle.h)\"",
)
assert "no shape either" in text

open(PATH, "w").write(text)
print(f"source rows stripped: {changed_src} (want 41)")
print(f"target rows stripped: {changed_tgt} (want 40: record 51 has no extent, B1134)")
print(f"override shape lines removed: {removed_shape} (want 30)")
for k in ('"lo"', '"hi"', '"halfWidth"', '"centroid"', '"spawnShape"', '"spawnExtents"', '"boneAt"', '"spiral"', '"discLo"'):
    print(f"remaining {k}: {text.count(k)}")
