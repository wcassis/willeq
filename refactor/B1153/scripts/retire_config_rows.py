#!/usr/bin/env python3
"""B1153: move the measured rows out of config/spell_effects.json.

Drops `spellOverrides` (the six blocks retire with their before/after
numbers in refactor/B1153/README.md), `sourceRecords.records` +
`sourceRecords.overrideRecords` (+ its `why`), `targetRecords.records` and
the whole `animRecords` block. The measured values themselves live on as
regression bands: the per-record anchor classes and the face onset in
tests/spell_fx_row_oracle.h (generated by gen_row_bands.py from this file at
e83a097d), the shapes in tests/spell_fx_shape_oracle.h, the populations in
tests/spell_fx_population_oracle.h, the timings in
tests/spell_fx_timing_oracle.h, and the field-145 record -> row mapping in
tests/spell_anim_rows.h.

What the file keeps is the NO-RECORD fallback only: `sourceRecords.default`
(the body cloud, the B1130 median onset, B1122's holds) and
`targetRecords.default` (the style volume on the target), plus the B1120
scale. Usage:
    python3 refactor/B1153/scripts/retire_config_rows.py <config>
Run it once, against the pre-retirement file (git show e83a097d:...).
"""
import json
import collections
import sys

p = sys.argv[1] if len(sys.argv) > 1 else "config/spell_effects.json"
doc = json.load(open(p), object_pairs_hook=collections.OrderedDict)

before = {
    "spellOverrides": sorted(doc["spellOverrides"].keys(), key=int),
    "sourceRecords.records": sorted(doc["sourceRecords"]["records"].keys(), key=int),
    "sourceRecords.overrideRecords": sorted(doc["sourceRecords"]["overrideRecords"].keys(), key=int),
    "targetRecords.records": sorted(doc["targetRecords"]["records"].keys(), key=int),
    "animRecords.rows": len(doc["animRecords"]["rows"]),
}
print("BEFORE:", json.dumps(before))

sr = doc["sourceRecords"]
sr["rule"] = ("B1153 (#473): the survey's per-record measured rows are retired -- "
    "every record is drawn by its spellsnew.eff record's EDD emitters (spellsnew.edd "
    "+0xA8 shape, +0xB8..+0xC0 offsets, +0xC4/+0xC8 tilts; B1149 population/sprite, "
    "B1150 shape, B1151 motion) and the measured values are regression bands in the "
    "tests/spell_fx_*_oracle.h headers (the generator: "
    "refactor/B1153/scripts/gen_row_bands.py, run against the pre-retirement config at "
    "e83a097d). What the file keeps is the NO-RECORD fallback: a spell whose field 145 "
    "is absent draws `default` (the style's body cloud on the caster, the B1130 median "
    "onset, B1122's holds), scaled by `scale`.")
sr["defaultWhy"] = ("A spell with no spellsnew.eff record (field 145 = 0) draws this "
    "row: the style's own body cloud (B1122) on the caster, from the B1130 median "
    "onset of the 40 records, holding B1122's measured holds past OP_Action "
    "(holdOther with another target, holdSelf on the caster; releaseCastGlow, which "
    "does not apply to record spells -- their slots run their own spellsnew.edd "
    "durations, B1145). B1153: the per-record measured rows (anchor classes, the "
    "computed 4.35 s holds) were the test seam's readers only; they are the bands in "
    "tests/spell_fx_row_oracle.h.")
del sr["records"]
del sr["overrideRecords"]
del sr["overrideRecordsWhy"]

tr = doc["targetRecords"]
tr["rule"] = ("B1153 (#473): the survey's per-record measured rows are retired -- "
    "every record lands as its spellsnew.eff record's Target stage (spellsnew.edd "
    "+0xA8 shape, +0xB8..+0xC0 offsets, +0xC4/+0xC8 tilts, depth +0xD0, +0x19C scale; "
    "B1149 population/sprite, B1150 shape, B1151 motion, B1152 the missile arrival) "
    "and the measured anchor classes and extents are regression bands in "
    "tests/spell_fx_row_oracle.h and tests/spell_fx_shape_oracle.h (the generator: "
    "refactor/B1153/scripts/gen_row_bands.py). What the file keeps is the NO-RECORD "
    "fallback: a spell whose field 145 is absent lands the style's own volume "
    "(spellComplete + impact) on the target's entity (`default`).")
tr["defaultWhy"] = ("A spell with no spellsnew.eff record (field 145 = 0) lands the "
    "style volume on the target's entity (the B1120 volume on the target). B1153: the "
    "survey's per-record anchors (record 5's head/face, 16/28's feet/ground, 3's "
    "column, 27/40/... 's caster) were honored as placement classes; they are the "
    "bands' evidence, and the record spells that drew them take their placement from "
    "the file.")
del tr["records"]

del doc["animRecords"]
del doc["spellOverrides"]

json.dump(doc, open(p, "w"), indent=2, ensure_ascii=False)
open(p, "a").write("\n")
json.load(open(p))
print("AFTER top keys:", list(doc.keys()))
print("AFTER sourceRecords keys:", list(doc["sourceRecords"].keys()))
print("AFTER targetRecords keys:", list(doc["targetRecords"].keys()))
