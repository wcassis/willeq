/*
 * B1002 (#322): the official client's per-window opacity, per window.
 *
 * The official Titanium client's UI XML (uifiles/default_old/EQUI_*.xml, 120
 * window files) sets <Style_Transparent> per window; the files with it true
 * (34 of 120, file-level: ANY element in the file) are the client's own
 * TRANSLUCENT windows, and the other 86 are opaque. Will's ruling (#322):
 * port this table VERBATIM, measure the one unknown (the blend alpha the
 * client applies to a Style_Transparent window) from the oracle, and make
 * the opaque windows fully hide what is under them.
 *
 * This header is fable's side of the table: each row is one fable static
 * window (UIWindow, ui_layout_table.h), the official window file it is a
 * port of, and that file's flag. kFableWindowFlags[i] is indexed by
 * UIWindow, exactly the way kUILayoutTable is.
 *
 * - OPAQUE windows (flag 0): the panel is drawn at full alpha 255; the
 *   lower window's text is ABSENT in the region it covers.
 * - TRANSLUCENT windows (flag 1): the panel is drawn at
 *   kTranslucentPanelAlpha, MEASURED from the official client's rendered
 *   Style_Transparent window over two known backdrops (refactor/B1002,
 *   scripts/eqemu/oracle/plans/b1002_alpha.tsv, solver
 *   refactor/B1002/solve_alpha.py). It supersedes B992's uniform 180.
 *
 * The pinned side: include/client/graphics/ui/official_window_flags.tsv is
 * the committed snapshot of the 120 flags (generated by
 * scripts/ui_flags/gen_window_flags.py from the oracle package's XMLs -- the
 * XMLs are client files and are never committed). tests/test_ui_window_flags
 * fails on ANY drift: a row here that disagrees with the snapshot names the
 * window, and a snapshot whose counts moved (120 total / 34 translucent /
 * 86 opaque) fails even if no fable window is affected.
 *
 * Every fable window is on a row (no "unaccounted" fable side), and every
 * official window is accounted for: mapped on a row here, or listed under
 * "not implemented in fable" in refactor/B1002/README.md.
 */

#pragma once

#include "client/graphics/ui/ui_layout_table.h"

#include <cstddef>

namespace EQT {
namespace Graphics {

// The measured translucent blend alpha (0..255). B1002: solved from the
// oracle's rendered chat window over two backdrops -- see the header's
// provenance note and refactor/B1002/README.md. B992's uniform 180 is
// superseded; the opaque windows below are at 255, not at 180.
constexpr uint8_t kTranslucentPanelAlpha = 180;  // MEASURED: see B1002 README

struct WindowFlagRow {
    const char* officialName;  // "EQUI_..." -- the file in the snapshot
    bool transparent;          // the file-level flag
};

// Indexed by UIWindow, in the same order as kUILayoutTable.
inline constexpr WindowFlagRow kFableWindowFlags[] = {
    {"EQUI_PlayerWindow",      false},  // PlayerStatus
    {"EQUI_TargetWindow",      false},  // Target
    {"EQUI_GroupWindow",       true },  // Group
    {"EQUI_PetInfoWindow",     false},  // Pet
    {"EQUI_BuffWindow",        true },  // Buffs
    {"EQUI_ChatWindow",        true },  // Chat
    {"EQUI_HotButtonWnd",      false},  // Hotbar
    {"EQUI_CastingWindow",     false},  // SpellGems
    {"EQUI_CastSpellWnd",      false},  // CastingBar
    {"EQUI_PlayerWindow",      false},  // XpBar (the XP line of the player frame)
    {"EQUI_CombatAbilityWnd",  false},  // CombatAbilities
    {"EQUI_Inventory",         true },  // Inventory (its ACP charm layer)
    {"EQUI_BookWindow",        true },  // Spellbook
    {"EQUI_SkillsWindow",      false},  // Skills
    {"EQUI_TradeskillWnd",     true },  // Tradeskill
    {"EQUI_MerchantWnd",       false},  // Merchant
    {"EQUI_LootWnd",           false},  // Loot
    {"EQUI_BankWnd",           false},  // Bank
    {"EQUI_TradeWnd",          false},  // Trade
    {"EQUI_GiveWnd",           false},  // Give
    {"EQUI_Container",         false},  // Container
    {"EQUI_ItemDisplay",       false},  // ItemDisplay
    {"EQUI_OptionsWindow",     false},  // Options
    {"EQUI_QuantityWnd",       false},  // Quantity
    {"EQUI_ConfirmationDialog",false},  // Confirmation
    {"EQUI_TrainWindow",       false},  // Trainer
    {"EQUI_TrackingWnd",       false},  // Tracking
    {"EQUI_TipWnd",            false},  // Tip
    {"EQUI_FriendsWnd",        false},  // Friends
};

static_assert(sizeof(kFableWindowFlags) / sizeof(kFableWindowFlags[0]) ==
                  static_cast<std::size_t>(UIWindow::Count),
              "every UIWindow has exactly one flag row");

/** The flag for a window: true = translucent (measured alpha), false = opaque (255). */
constexpr bool windowIsTranslucent(UIWindow w) {
    return kFableWindowFlags[static_cast<std::size_t>(w)].transparent;
}

/** The panel alpha a window's drawPanel() uses. */
constexpr uint8_t windowPanelAlpha(UIWindow w) {
    return windowIsTranslucent(w) ? kTranslucentPanelAlpha : 255;
}

}  // namespace Graphics
}  // namespace EQT
